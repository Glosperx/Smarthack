create table if not exists turbine_mentenance(
    entry_id bigint generated by default as identity primary key,
    predicted_date date not null,
    daily_fault_probability real not null,
    cumulative_fault_probability real not null,
    status text not null,
    suspected_subsystem text not null,
    turbine_id bigint not null,
    constraint turbine_turbine_mentenance_fk foreign key (turbine_id) references turbine(id)
);